const presets: PresetDTO[] = expansionHeroes.map((hero) => {
  const template = coreCatalog.presets.find(
    (p) => p.presetId === templates[hero.id as keyof typeof templates],
  )!;
  return {
    ...template,
    presetId: hero.id.replace(/^H_/, "D_") as PresetDTO["presetId"],
    heroId: hero.id,
    name: hero.nameVi,
    contentVersion: "heroes_v1",
    entries: structuredClone(template.entries),
    strategyKey: `presets.${hero.id}.strategy`,
  };
});

export const heroesCatalog: Catalog = {
  ...coreCatalog,
  version: "heroes_v1",
  heroes: [...coreCatalog.heroes, ...expansionHeroes],
  powers: [...coreCatalog.powers, ...expansionPowers],
  presets: [
    ...coreCatalog.presets.map((p) => ({ ...p, contentVersion: "heroes_v1" })),
    ...presets,
  ],
};
